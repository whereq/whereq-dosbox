#!/usr/bin/env python3
"""Turn a TrueType font into the 8x8 bitmap the DOS demo draws its text with.

The demo runs in VGA mode 13h, where there is no text mode and no BIOS font
to lean on: every glyph has to be blitted into video memory by hand.  This
script renders the glyphs once and writes them out as a table of bytes.

    python3 tools/mkfont.py src/font8x8.inc

The result is checked by rendering the *bytes* back into a PNG, so what the
script says it produced is what the game will show.
"""

import os
import sys

from PIL import Image, ImageDraw, ImageFont

# Liberation Mono is metric compatible with Courier New and is installed on
# most Linux systems.  Only the rendered pixels end up in the game - no font
# file is copied, so nothing has to be licensed along with it.
FONT = "/usr/share/fonts/truetype/liberation/LiberationMono-Regular.ttf"

SIZE = 10         # point size to render at
CELL_W = 6        # pixels per character cell
CELL_H = 8        # rows per character cell
BASELINE = 7      # row the glyphs stand on
FIRST, LAST = 32, 126


def build():
    font = ImageFont.truetype(FONT, SIZE)
    ascent, descent = font.getmetrics()

    glyphs = {}
    for code in range(FIRST, LAST + 1):
        char = chr(code)
        # Draw on a canvas, then move the ink so that it stands on the
        # baseline of the cell.
        probe = Image.new("L", (SIZE * 2, SIZE * 2 + descent), 0)
        ImageDraw.Draw(probe).text((0, 0), char, font=font, fill=255)
        box = probe.getbbox()
        if box is None:
            glyphs[code] = [0] * CELL_H
            continue

        left, top, right, bottom = box
        width = right - left
        height = bottom - top

        cell = Image.new("L", (CELL_W, CELL_H), 0)
        # Centre the glyph in the cell, standing on the baseline.
        x = max(0, (CELL_W - width) // 2)
        y = BASELINE - (bottom - top)
        if y < 0:
            # Too tall for the cell: cut the top off, it is the accent that
            # goes, not the body of the letter.
            cut = -y
            y = 0
            height -= cut
        glyph = Image.new("L", (width, max(1, height)), 0)
        glyph.paste(probe.crop((left, top, right, bottom)), (0, 0))
        cell.paste(glyph, (x, y))
        glyphs[code] = [
            sum(1 << (7 - px) for px in range(CELL_W) if cell.getpixel((px, row)) >= 96)
            for row in range(CELL_H)
        ]
    return glyphs


def as_assembly(glyphs):
    out = []
    out.append("# Generated by tools/mkfont.py - do not edit by hand.")
    out.append("# 8x8 bitmap font, one byte per row, most significant bit left.")
    out.append("# The character codes run from 32 to 126, so the glyph for a")
    out.append("# character is at font_data + (code - 32) * 8.")
    out.append("")
    out.append("font_data:")
    for code in range(FIRST, LAST + 1):
        char = chr(code)
        name = char if char.isprintable() and char not in '"\\' else "."
        rows = glyphs[code]
        body = ", ".join("0x%02x" % b for b in rows)
        out.append("    .byte %-30s # %3d '%s'" % (body, code, name))
    out.append("")
    return "\n".join(out)


def preview(glyphs, path):
    """Render the bytes back, so the preview shows what the game draws."""
    columns = 32
    rows = (len(glyphs) + columns - 1) // columns
    img = Image.new("L", (columns * CELL_W, rows * CELL_H), 0)
    px = img.load()
    for index, code in enumerate(sorted(glyphs)):
        cx = (index % columns) * CELL_W
        cy = (index // columns) * CELL_H
        for row, bits in enumerate(glyphs[code]):
            for column in range(CELL_W):
                if bits & (1 << (7 - column)):
                    px[cx + column, cy + row] = 255
    img = img.resize((img.width * 4, img.height * 4), Image.NEAREST)
    img.save(path)
    print("preview: %s (%d glyphs)" % (path, len(glyphs)))


def main():
    target = sys.argv[1] if len(sys.argv) > 1 else "font8x8.inc"
    with open(target, "w") as handle:
        handle.write(as_assembly(build()))
    print("wrote %s" % target)
    preview(build(), os.path.splitext(target)[0] + ".png")


if __name__ == "__main__":
    main()
